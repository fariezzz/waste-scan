<h3>🔄 Cara Mengelola Sampah Anorganik</h3>

<p>
    Agar tidak mencemari lingkungan, sampah anorganik <strong>tidak boleh dibuang sembarangan</strong>. Berikut cara
    pengelolaannya:
</p>

<ol>
    <li>Pisahkan sampah anorganik dari sampah organik.</li>
    <li>Cuci sampah anorganik yang kotor agar dapat didaur ulang.</li>
    <li>Kumpulkan sampah plastik, botol, dan logam ke <strong>bank sampah</strong> atau tempat daur ulang.</li>
    <li>Gunakan kembali barang-barang yang masih layak dipakai (reuse).</li>
    <li>Kurangi penggunaan plastik sekali pakai (reduce).</li>
</ol>

<h4 class="mt-4">📦 Contoh Pemanfaatan Ulang</h4>

<ul>
    <li>Botol plastik → pot tanaman</li>
    <li>Karton → kerajinan atau tempat penyimpanan</li>
    <li>Kain bekas → eco-brick atau kerajinan</li>
</ul>

