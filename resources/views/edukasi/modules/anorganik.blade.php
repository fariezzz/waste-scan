<p>
    Sampah anorganik adalah sampah yang <strong>tidak mudah terurai</strong> oleh mikroorganisme dan membutuhkan waktu
    yang sangat lama untuk terdegradasi — mulai dari puluhan hingga ribuan tahun.
</p>

<hr>

<h3>🟥 Contoh Sampah Anorganik</h3>

<ul>
    <li>Plastik (botol minum, kemasan makanan, sampah sachet)</li>
    <li>Kaca (botol kaca, pecahan gelas)</li>
    <li>Logam (kaleng minuman, alumunium foil)</li>
    <li>Karet dan sintetis (ban, mainan plastik)</li>
    <li>Styrofoam</li>
</ul>

