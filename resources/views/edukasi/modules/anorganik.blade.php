<h3>💡 Kesimpulan</h3>

<p>
    Sampah anorganik adalah salah satu penyebab terbesar pencemaran lingkungan. Dengan membiasakan diri
    melakukan <strong>reduce, reuse, recycle (3R)</strong>, kita dapat membantu mengurangi jumlah sampah yang
    mencemari bumi dan menjaga lingkungan tetap bersih serta berkelanjutan.
</p>