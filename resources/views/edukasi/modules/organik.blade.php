<p>
    Sampah organik adalah sampah yang berasal dari makhluk hidup (alami), bersifat <strong>mudah terurai</strong>
    melalui proses biologis seperti pembusukan oleh mikroorganisme.
</p>

<hr>

<h3>🟩 Contoh Sampah Organik</h3>
<ul>
    <li>Sisa makanan</li>
    <li>Daun dan ranting kering</li>
    <li>Buah busuk</li>
    <li>Sisa sayuran</li>
    <li>Kulit telur</li>
</ul>

