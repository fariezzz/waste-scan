<h3>♻ Cara Mengolah Sampah Organik Menjadi Kompos</h3>

<ol>
    <li>Kumpulkan sampah organik yang kering dan basah.</li>
    <li>Potong kecil-kecil agar mudah terurai.</li>
    <li>Campurkan dengan tanah atau aktivator mikroba.</li>
    <li>Semprot dengan air untuk menjaga sampah tetap lembab, tapi tidak sampai basah.</li>
    <li>Diamkan 2–4 minggu sambil diaduk 2–3 hari sekali.</li>
</ol>

<h4 class="mt-3">Hasil Kompos</h4>
<p>
    Setelah 3–4 minggu akan terbentuk kompos berwarna gelap, tidak bau, dan bisa digunakan untuk pupuk tanaman.
</p>

